#!/usr/bin/env node
'use strict';

// Builds cutscene-provenance-data.js from the parent repository's launch
// provenance trace (docs/reviews/cutscene-launch-provenance-20260927): for
// every Director scene, the event-directory rows that launch it and the
// scenario / mission / world-map node those rows belong to. The UI shows this
// as "Loads from …" and the scene search matches those names.
//
// Usage: node tools/generate-cutscene-provenance-data.js [--source <dir>] [--check]

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const editorRoot = path.resolve(__dirname, '..');
const { PARENT } = require(path.join(editorRoot, 'tests', 'project-paths.cjs'));
const defaultSource = path.join(PARENT, 'docs', 'reviews', 'cutscene-launch-provenance-20260927');
const output = path.join(editorRoot, 'cutscene-provenance-data.js');

function parseArgs(argv) {
  const options = { source: defaultSource, check: false };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--source') options.source = path.resolve(argv[++index]);
    else if (argv[index] === '--check') options.check = true;
    else throw new Error('Unknown argument ' + argv[index]);
  }
  return options;
}

function sha256(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex').toUpperCase();
}

function text(value) {
  return typeof value === 'string' && value.trim() ? value.trim() : null;
}

function build(sourceDir) {
  const rowsPath = path.join(sourceDir, 'event-row-provenance.json');
  const scenesPath = path.join(sourceDir, 'scene-provenance.json');
  const rowsRaw = fs.readFileSync(rowsPath);
  const scenesRaw = fs.readFileSync(scenesPath);
  const rowList = JSON.parse(rowsRaw.toString('utf8'));
  const sceneMap = JSON.parse(scenesRaw.toString('utf8'));
  if (!Array.isArray(rowList)) throw new Error('event-row-provenance.json must be an array');
  const rows = {};
  rowList.forEach(entry => {
    if (!Number.isInteger(entry.row)) throw new Error('row entry without an integer row');
    rows[entry.row] = {
      role: text(entry.role),
      missionOrScenario: text(entry.missionOrScenario),
      wikiMissionId: entry.wikiMissionId == null ? null : entry.wikiMissionId,
      chapter: entry.chapter == null ? null : entry.chapter,
      worldMapNode: text(entry.worldMapNode),
      confidence: text(entry.confidence),
      sceneCount: Array.isArray(entry.directorScenes) ? entry.directorScenes.length : 0
    };
  });
  const scenes = {};
  Object.keys(sceneMap).sort().forEach(assetId => {
    const launches = Array.isArray(sceneMap[assetId]) ? sceneMap[assetId] : [];
    scenes[assetId] = launches.map(launch => ({
      row: Number.isInteger(launch.row) ? launch.row : null,
      missionOrScenario: text(launch.missionOrScenario),
      worldMapNode: text(launch.worldMapNode),
      confidence: text(launch.confidence)
    }));
  });
  return {
    schemaVersion: 1,
    source: {
      directory: 'docs/reviews/cutscene-launch-provenance-20260927',
      eventRowProvenanceSha256: sha256(rowsRaw),
      sceneProvenanceSha256: sha256(scenesRaw)
    },
    counts: { rows: Object.keys(rows).length, scenes: Object.keys(scenes).length },
    rows,
    scenes
  };
}

function render(data) {
  return '// Generated by tools/generate-cutscene-provenance-data.js from the parent\n' +
    '// repository\'s cutscene launch provenance trace. Do not edit by hand.\n' +
    'window.OB64 = window.OB64 || {};\n' +
    'window.OB64.cutsceneProvenance = ' + JSON.stringify(data) + ';\n';
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const rendered = render(build(options.source));
  if (options.check) {
    const existing = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : null;
    if (existing !== rendered) {
      console.error('cutscene-provenance-data.js is stale for ' + options.source);
      process.exit(1);
    }
    console.log('cutscene-provenance-data.js matches ' + options.source);
    return;
  }
  fs.writeFileSync(output, rendered);
  const data = build(options.source);
  console.log('Wrote ' + output + ': ' + data.counts.rows + ' event rows, ' +
    data.counts.scenes + ' scenes.');
}

if (require.main === module) main();

module.exports = { build, render };
