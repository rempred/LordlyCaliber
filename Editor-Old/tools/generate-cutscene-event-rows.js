'use strict';

// Pins the retail parent event rows that Cutscene Studio may relocate when it
// binds a scene to an event launch site. Each populated row records its retail
// resource key, stored and decoded sizes, decoded SHA-256, and the decoded
// offsets of its short-form launch sites (68 NN 10 00). Export and reopen
// verify every retail preimage against this table before using it.
//
// Usage: node tools/generate-cutscene-event-rows.js [--rom <master.v64>] [--output <file>]

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const EDITOR = path.resolve(__dirname, '..');
const RESOURCE_BASE_Z64 = 0x00594280;
const EVENT_DIRECTORY_Z64 = 0x009398E8;
const EVENT_ROWS = 115;

function parseArgs(argv) {
  const options = {
    rom: path.join(require(path.join(EDITOR, 'tests', 'project-paths.cjs')).PARENT,
      'Ogre Battle 64 - Person of Lordly Caliber (U) [!].v64'),
    output: path.join(EDITOR, 'cutscene-event-rows-data.js')
  };
  for (let index = 0; index < argv.length; index += 1) {
    const field = { '--rom': 'rom', '--output': 'output' }[argv[index]];
    if (!field || index + 1 >= argv.length) throw new Error('Unknown or incomplete argument ' + argv[index]);
    options[field] = path.resolve(argv[++index]);
  }
  return options;
}

function readU32(bytes, at) {
  return ((bytes[at] << 24) | (bytes[at + 1] << 16) | (bytes[at + 2] << 8) | bytes[at + 3]) >>> 0;
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  global.window = global;
  vm.runInThisContext('var OB64 = window.OB64 = {};');
  for (const file of ['cutscene-model.js', 'cutscene-codec.js']) {
    vm.runInThisContext(fs.readFileSync(path.join(EDITOR, file), 'utf8'), { filename: file });
  }
  const raw = fs.readFileSync(options.rom);
  const z64 = raw[0] === 0x80 ? Uint8Array.from(raw) : Uint8Array.from(raw, (_, index) => raw[index ^ 1]);
  if (readU32(z64, EVENT_DIRECTORY_Z64) !== EVENT_ROWS * 4) throw new Error('The event directory no longer has 115 rows.');
  const rows = [];
  let longSites = 0;
  let shortSites = 0;
  for (let row = 0; row < EVENT_ROWS; row += 1) {
    const key = readU32(z64, EVENT_DIRECTORY_Z64 + 4 + row * 4);
    if (!key) { rows.push(null); continue; }
    const prefix = RESOURCE_BASE_Z64 + key;
    const storedLength = readU32(z64, prefix);
    const decoded = OB64.cutsceneCodec.decodeCustomLz(z64.slice(prefix + 4, prefix + 4 + storedLength),
      { requireExact: true }).bytes;
    const shortOffsets = [];
    for (let offset = 4; offset + 1 < decoded.length; offset += 2) {
      if (decoded[offset] !== 0x10 || decoded[offset + 1] !== 0x00) continue;
      if (decoded[offset - 4] === 0x68 && decoded[offset - 2] === 0x88) longSites += 1;
      else if (decoded[offset - 2] === 0x68) { shortSites += 1; shortOffsets.push(offset); }
    }
    rows.push({
      key,
      storedLength,
      decodedLength: decoded.length,
      decodedSha256: crypto.createHash('sha256').update(decoded).digest('hex').toUpperCase(),
      shortSites: shortOffsets
    });
  }
  if (longSites !== 1596 || shortSites !== 402) {
    throw new Error('Expected 1,596 long and 402 short launch sites; found ' + longSites + ' and ' + shortSites + '.');
  }
  const data = {
    format: 'ob64-cutscene-event-rows',
    schemaVersion: 1,
    sourceRevision: 'us-rev0',
    resourceBaseZ64: RESOURCE_BASE_Z64,
    directoryZ64: EVENT_DIRECTORY_Z64,
    rowCount: EVENT_ROWS,
    launchSites: { long: longSites, short: shortSites },
    rows
  };
  const output = '// Generated by tools/generate-cutscene-event-rows.js. Do not edit by hand.\n' +
    'window.OB64 = window.OB64 || {};\n' +
    'window.OB64.cutsceneEventRows = ' + JSON.stringify(data) + ';\n';
  fs.writeFileSync(options.output, output);
  console.log('Wrote ' + options.output + ': ' + rows.filter(Boolean).length + ' rows, ' +
    longSites + ' long and ' + shortSites + ' short launch sites.');
}

main();
