'use strict';
// Authenticated accepted ASM -> maintained source, plus hashes, never a game binary bundle.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),cp=require('node:child_process');
const mips=require('./lib/symbolic-mips.cjs'),root=path.resolve(__dirname,'../..');
const rom=fs.readFileSync(process.argv[2]),reference=fs.readFileSync(process.argv[3],'utf8');
if(rom.readUInt32BE(0)===0x37804012)rom.swap16();
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
if(hash(rom)!=='571e83396bc81e70da4c0a20313d82dbd7dfe685f2c37418c8e27f927e2cc67a')throw Error('US Rev0 required');
const start=0x13c060,end=0x13c49c,ram=0x801e7920,calls={service_8009da50:0x8009da50};
const descriptor=0x387c0+7*40;
if(rom.readUInt32BE(descriptor)+(start-rom.readUInt32BE(descriptor+8))!==ram ||
   start<rom.readUInt32BE(descriptor+8)||end>rom.readUInt32BE(descriptor+12))throw Error('Dispatcher overlay placement differs');
const rows=mips.rows(reference,rom,start,end);
const parameters=new Map([[0x13c1e8,'LC_DIVISOR_HI'],[0x13c1ec,'LC_DIVISOR_LO']]);
const gate=[
 'bne $v0, $zero, L_13c208','lui $s0, LC_ALTERNATE_HI',
 'beq $zero, $zero, L_13c210','ori $s0, $s0, LC_ALTERNATE_LO',
 'lui $s0, LC_NORMAL_HI','ori $s0, $s0, LC_NORMAL_LO',
 'jal service_80092a60','nop','divu $zero, $v0, $s1','mfhi $v1',
 'sltu $v1, $v1, $s0','nop','beq $v1, $zero, L_13c46c','addiu $v1, $zero, 29'];
const scenarioGate=[
 'lui $a0, LC_SCENARIO_HI','ori $a0, $a0, LC_SCENARIO_LO',
 'lui $v0, 0x8019','lbu $v0, -0xb7f($v0)','sll $v0, $v0, 4',
 'addu $a0, $a0, $v0','addiu $a1, $sp, 0x20','jal service_8009da50',
 'addiu $a2, $zero, 16','jal service_80186210','addiu $a0, $zero, 17',
 'sltu $v0, $zero, $v0','sll $v0, $v0, 3','addu $v0, $sp, $v0',
 'lw $s1, 0x20($v0)','lw $s0, 0x24($v0)','j L_13c270','nop'];
// s3 starts at30, is decremented exactly once per candidate, and loops only
// while nonzero. The original division's zero/negative-overflow checks cannot
// be reached with valid loop state. Retain remainder at290 and all later code.
// The global helper's jump at28c also executes mfhi s4 as its delay; s4 has no
// live value until the candidate draw overwrites it.
const scenarioHelper=['j L_13c290','divu $zero, $v0, $s3',
 'jal service_80092a60','nop','divu $zero, $v0, $s1','mfhi $v1',
 'sltu $v1, $v1, $s0','beq $v1, $zero, L_13c46c',
 'addiu $v1, $zero, 29','j L_13c230'];
const out=['/* Generated by native/tools/generate-encounter-source.cjs from accepted',
 ' * func_0013C060.s. ROM13C060 -> observed RAM801E7920.',
 ' * LC_NATIVE_GATE selects the maintained count-based global roll.',
 ' * LC_SCENARIO_RATES selects ROM-backed effective per-scenario rates.',
 ' * All original function positions and other behavior remain intact. */',
 '.set noat','.set noreorder'];
for(const row of rows){
  const original=mips.instruction(row,{start,end,ram,parameters,calls});
  out.push(mips.label(row.at)+':');
  const scenario = row.at>=0x13c1e8&&row.at<0x13c230 ? scenarioGate[(row.at-0x13c1e8)/4]
    : row.at>=0x13c268&&row.at<0x13c290 ? scenarioHelper[(row.at-0x13c268)/4] : null;
  if(scenario)out.push('.if LC_SCENARIO_RATES','    '+scenario,'.else');
  if(row.at>=0x13c1f8&&row.at<0x13c230)out.push('.if LC_NATIVE_GATE','    '+gate[(row.at-0x13c1f8)/4],'.else','    '+original,'.endif');
  else out.push('    '+original);
  if(scenario)out.push('.endif');
}
const source=out.join('\n')+'\n',output=path.join(root,'native/game/encounters');
fs.mkdirSync(output,{recursive:true});fs.writeFileSync(path.join(output,'dispatcher.s'),source);
const fields=[
 [0x13c1e8,'divisor','high'],[0x13c1ec,'divisor','low'],
 [0x13c1fc,'alternatePassCount','high'],[0x13c204,'alternatePassCount','low'],
 [0x13c208,'normalPassCount','high'],[0x13c20c,'normalPassCount','low']
].map(([at,key,half])=>({offset:at-start,key,half}));
// Local developer validation with the same authenticated compiler used by export.
const tools=path.resolve(process.argv[4]),pins=JSON.parse(fs.readFileSync(path.join(root,'native/rebuild/toolchain.json'))).tools;
for(const [name,expected] of Object.entries(pins))if(hash(fs.readFileSync(path.join(tools,name)))!==expected.toLowerCase())throw Error('Compiler identity mismatch: '+name);
const build=path.join(root,'native/build/encounter-source');fs.mkdirSync(build,{recursive:true});
fs.writeFileSync(path.join(build,'owner.ld'),Object.entries(calls).map(([n,a])=>`${n} = 0x${a.toString(16)};`).join('\n')+`\nSECTIONS { .owner 0x${ram.toString(16)} : { *(.owner) } }\n`);
function assemble(native,scenario=false){
 const name=scenario?'scenario':native?'native':'retail',base=path.join(build,name);
 const defs=`.equ LC_SCENARIO_RATES,${scenario?1:0}\n.equ LC_SCENARIO_HI,640\n.equ LC_SCENARIO_LO,0\n.equ LC_NATIVE_GATE,${native?1:0}\n.equ LC_DIVISOR_HI,1\n.equ LC_DIVISOR_LO,6464\n.equ LC_NORMAL_HI,0\n.equ LC_NORMAL_LO,51\n.equ LC_ALTERNATE_HI,0\n.equ LC_ALTERNATE_LO,11\n`;
 fs.writeFileSync(base+'.s','.section .owner,"ax"\n.balign 4\n'+defs+source);
 cp.execFileSync(path.join(tools,'mips-kmc-elf-as.exe'),['--vr4300mul-off','-G','0','-mips3','-mabi=32','-EB','-o',base+'.o',base+'.s']);
 cp.execFileSync(path.join(tools,'mips-kmc-elf-ld.exe'),['-EB','-T',path.join(build,'owner.ld'),'-o',base+'.elf',base+'.o']);
 cp.execFileSync(path.join(tools,'mips-kmc-elf-objcopy.exe'),['-O','binary',...['.text','.data','.bss','.reginfo','.mdebug','.pdr','.comment'].map(s=>'--remove-section='+s),base+'.elf',base+'.bin']);
 return fs.readFileSync(base+'.bin');
}
const retail=assemble(false);if(!retail.equals(rom.subarray(start,end)))throw Error('Compiled retail dispatcher mismatch');
const native=assemble(true);if(native.length!==end-start)throw Error('Native dispatcher exceeds original extent');
const masked=Buffer.from(native);for(const f of fields)masked.writeUInt16BE(0,f.offset+2);
const scenario=assemble(true,true);if(scenario.length!==end-start)throw Error('Scenario dispatcher exceeds original extent');
const scenarioMasked=Buffer.from(scenario);for(const at of [0x13c1ea,0x13c1ee])scenarioMasked.writeUInt16BE(0,at-start);
fs.writeFileSync(path.join(output,'dispatcher.json'),JSON.stringify({
 generator:'native/tools/generate-encounter-source.cjs',input:'Accepted Decomp ASM func_0013C060.s; US Rev0 z64 SHA256 '+hash(rom),
 start,size:end-start,address:ram,retailSha256:hash(retail),nativeMaskedSha256:hash(masked),scenarioMaskedSha256:hash(scenarioMasked),fields,calls,
 dma:{start:0x2de50,size:164,sha256:hash(rom.subarray(0x2de50,0x2def4))},
 overlay:{start:descriptor,size:40,sha256:hash(rom.subarray(descriptor,descriptor+40))},
 random:{start:0x22e60,size:44,address:0x80092a60,outputBits:30,sha256:hash(rom.subarray(0x22e60,0x22e8c))}
},null,2)+'\n');
console.log(`Compiled ${rows.length} dispatcher instructions; retail exact, global/scenario modes same extent, ${fields.length} global parameter halves`);
