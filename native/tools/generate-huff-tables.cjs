'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../..'),source=fs.readFileSync(path.join(root,'cutscene-njpg.js'),'utf8');
const start=source.indexOf('var HUFFMAN_SPECS ='),end=source.indexOf('function NjpgError',start);
if(start<0||end<start)throw Error('HUFF table source was not found');
const context={hexBytes:s=>s.trim().split(/\s+/).map(v=>parseInt(v,16))};vm.createContext(context);
vm.runInContext(source.slice(start,end),context);
let out='// Generated by native/tools/generate-huff-tables.cjs from cutscene-njpg.js.\n// Standard JPEG entropy tables; no ROM payloads.\n#pragma once\n#include <array>\nnamespace lordly::huff {\n';
for(const [name,spec] of Object.entries(context.HUFFMAN_SPECS))for(const field of ['bits','values']){
 const values=spec[field];out+=`inline constexpr std::array<int, ${values.length}> ${name}_${field} = {${values.join(', ')}};\n`;
}
out+='}\n';fs.writeFileSync(path.join(root,'native/engine/huff_tables.h'),out);
