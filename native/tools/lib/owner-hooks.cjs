'use strict';
// Keep only bounded mod blocks from the authenticated generator's instruction
// stream. The complete original function is supplied by accepted C at export.
const fs = require('node:fs'), path = require('node:path');
module.exports = function writeHooks(source, output, name, start, address, ranges) {
  return ranges.map(([first, last], index) => {
    const begin = source.indexOf(`L_${first.toString(16)}:\n`);
    const end = source.indexOf(`L_${last.toString(16)}:\n`);
    if (begin < 0 || end <= begin || (first | last) & 3) throw Error('Invalid hook bounds');
    const body = source.slice(begin, end);
    const labels = new Set([...body.matchAll(/^(L_[0-9a-f]+):/gm)].map(m => m[1]));
    const symbols = {};
    for (const match of body.matchAll(/\bL_([0-9a-f]+)\b/g))
      if (!labels.has(match[0])) symbols[match[0]] = address + parseInt(match[1], 16) - start;
    const file = `${name}-hook-${index}.s`;
    fs.writeFileSync(path.join(output, file),
      `/* Bounded ${name} mod hook. Generated by native/tools/generate-${name === 'dispatcher' ? 'encounter' : 'reward'}-source.cjs. */\n` + body);
    return {offset: first - start, size: last - first, source: file, symbols};
  });
};
