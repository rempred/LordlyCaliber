#!/usr/bin/env python3
"""Translate the maintained OBSO producer to GAS source and compatibility metadata.

Developer input: parent tools/generate_editor_combat_animation_override_data.py
and its maintained v2 builder, plus this checkout's browser compatibility catalog.
Users need only the resulting source/metadata; no parent or Decomp checkout.
No game-code binaries are written or embedded in the generated product files.
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--parent', type=Path, required=True)
    args = parser.parse_args()
    native = Path(__file__).resolve().parents[1]
    parent = args.parent.resolve()
    producer = parent / 'tools/generate_editor_combat_animation_override_data.py'
    spec = importlib.util.spec_from_file_location('lordly_obso_producer', producer)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    v2 = module.V2
    captured = []
    original = v2.Assembler

    class Capture(original):
        def assemble(self):
            captured.append(self)
            return super().assemble()

    v2.Assembler = Capture
    target = native / 'game/art'
    target.mkdir(parents=True, exist_ok=True)
    symbols = {
        v2.ICACHE_INVALIDATE_RAM: 'LC_ICACHE_INVALIDATE',
        v2.DCACHE_INVALIDATE_RAM: 'LC_DCACHE_INVALIDATE',
        v2.MODE_RETURN_ENTRY_RAM: 'LC_MODE_RETURN',
        v2.MODULE_ENTRY_RAM: 'LC_MODULE_ENTRY',
        v2.ORIGINAL_PROLOGUE_LIVE: 'LC_ORIGINAL_PROLOGUE',
    }
    sources = {}
    for name, builder, size in [
        ('bootstrap', module.build_v3_bootstrap, v2.BOOT_CAPACITY),
        ('lookup', module.build_v3_module_code, None),
        ('mode-return', v2.build_mode_return_code, None),
    ]:
        compiled = builder()
        a = captured[-1]
        lines = [
            '# Generated by native/tools/generate-animation-overrides.py.',
            '# Symbolic instructions from the maintained OBSO producer.',
            '# The editor assembles this source during user export.',
            'lc_source_begin:',
        ]
        bindings = {}
        for item in a.items:
            op = item[0]
            if op == 'label':
                lines.append(item[1] + ':')
                continue
            *operands, note = item[1:]
            if op in {'lw', 'sw', 'lbu', 'lhu', 'sb'}:
                text = f'${operands[0]}, {operands[1]}(${operands[2]})'
            elif op in {'j', 'jal'}:
                operand = operands[0]
                if isinstance(operand, int):
                    label = symbols[operand]
                    bindings[label] = operand
                    text = label
                else:
                    text = operand
            else:
                text = ', '.join('$' + x if isinstance(x, str) and x in v2.REG else str(x)
                                 for x in operands)
            lines.append('    ' + op + (' ' + text if text else '') +
                         (' # ' + note.replace('v2', 'v3') if note else ''))
        if size is not None:
            lines.append(f'    .space {size} - (. - lc_source_begin), 0')
        data = compiled.data
        if size is not None:
            data += bytes(size-len(data))
        filename = f'animation-override-{name}.s'
        (target/filename).write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
        sources[name] = {'file':'game/art/'+filename,'address':compiled.base,
                         'size':len(data),'sha256':digest(data),'symbols':bindings}

    # Installation and removal use source-built instructions too. Conditional
    # constants are supplied to the assembler before this text, not by the linker.
    fragments = {
        'entry': ('j LC_LOOKUP\nnop\n', v2.MODULE_ENTRY_RAM,
                  {'LC_LOOKUP':v2.MODULE_RAM+0x200}),
        'hook': ('.if LC_INSTALLED\nj LC_BOOT\nnop\n.else\nlui $v0, 0x801d\nlw $v0, -0x1740($v0)\n.endif\n',
                 v2.HOOK_LIVE, {'LC_BOOT':v2.BOOT_RAM}),
        'return': ('.if LC_INSTALLED\nj LC_BOOT_SELECTOR\nnop\n.else\njr $ra\nnop\n.endif\n',
                   v2.SELECTOR_RETURN_LIVE, {'LC_BOOT_SELECTOR':v2.BOOT_SELECTOR_ENTRY_RAM}),
        'carriers': ('.if LC_INSTALLED\nori $v0, $s1, 0\nori $v0, $s1, 0\nori $s0, $v0, 0\nandi $a1, $s0, 255\nori $s2, $v0, 0\nandi $a1, $s2, 255\n.else\nandi $v0, $s1, 255\nandi $v0, $s1, 255\nandi $s0, $v0, 255\naddu $a1, $s0, $zero\nandi $s2, $v0, 255\naddu $a1, $s2, $zero\n.endif\n',
                     0x80000000, {}),
    }
    for name, (source, address, bindings) in fragments.items():
        filename = f'animation-override-{name}.s'
        (target/filename).write_text('# Generated by native/tools/generate-animation-overrides.py.\n'+source,
                                    encoding='utf-8', newline='\n')
        sources[name] = {'file':'game/art/'+filename,'address':address,'symbols':bindings}

    # Node reads only the already generated browser catalog and emits structured
    # descriptive metadata plus hashes; compiled module/ROM bytes are excluded.
    script = r'''
const fs=require('node:fs'),vm=require('node:vm'),crypto=require('node:crypto');
const context={window:{OB64:{}}};context.OB64=context.window.OB64;vm.createContext(context);
vm.runInContext(fs.readFileSync(process.argv[1],'utf8'),context);
const d=context.OB64.COMBAT_ANIMATION_OVERRIDE_DATA;
const sha=hex=>crypto.createHash('sha256').update(Buffer.from(hex,'hex')).digest('hex');
const versions=[d.legacyV1,d.legacyV2,d].map((v,i)=>({version:i+1,
  bootstrapSize:v.bootstrapSize||d.layout.bootstrapSize,bootstrapSha256:sha(v.bootstrapHex),
  hookSha256:sha(v.ownedHookHex),moduleTemplateSha256:sha(v.moduleTemplateHex)}));
const result={version:1,layout:d.layout,versions,actions:d.actions,
  classes:d.classes.map(c=>({id:c.id,source:c.sourceArt,owner:c.rawOwner})),
  sites:[{name:'hook',offset:d.layout.hookZ64,size:8,retailSha256:sha(d.retailHookHex),activeSha256:sha(d.ownedHookHex)},
    {name:'return',offset:d.layout.selectorReturnZ64,size:8,retailSha256:sha(d.selectorReturnPreimageHex),activeSha256:sha(d.selectorReturnPostimageHex)},
    ...d.carrierPatches.map((c,i)=>({name:'carrier'+i,offset:c.z64,size:4,retailSha256:sha(c.preimageHex),activeSha256:sha(c.postimageHex)}))]};
process.stdout.write(JSON.stringify(result));
'''
    data = json.loads(subprocess.check_output(['node','-e',script,str(native.parent/'combat-animation-overrides-data.js')]))
    data['sources'] = sources
    data['generator'] = 'native/tools/generate-animation-overrides.py'
    data['inputs'] = [{'path':str(path.relative_to(parent)).replace('\\','/'),
                       'sha256':digest(path.read_bytes())} for path in
                      [producer,parent/'tools/build_combat_body_animation_selector_override_rom.py']]
    (target/'animation-overrides.json').write_text(json.dumps(data,indent=2)+'\n', encoding='utf-8', newline='\n')
    print(f'Generated {len(sources)} symbolic assembly sources and compatibility metadata.')


if __name__ == '__main__':
    main()
