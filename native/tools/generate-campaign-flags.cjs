'use strict';
// Qualify bounded resident road flags without changing their owner allocations.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const compile=require('./lib/compile-owned-c.cjs'),{digest}=require('./decomp-evidence.cjs');
const native=path.resolve(__dirname,'..'),catalog=require('../game/accepted/rom-owners.json');
const accepted=catalog.sources.find(g=>g.name==='func_00048abc');assert(accepted);
const original=fs.readFileSync(path.join(native,accepted.source));assert.equal(digest(original),accepted.sourceSha256);
let getter=original.toString().replace(/\r\n/g,'\n');
const old='if (temp_v1_8 < 0) {\n        var_v0_10 = temp_a0_7 + 6;\n    }';assert(getter.includes(old));
getter=getter.replace('int var_v0_10;','int var_v0_10;\n    int result = 0;')
 .replace('temp_a0_7 = arg0 & 0xFF;','temp_a0_7 = arg0;')
 .replace(old,'if ((unsigned int)temp_v1_8 < 40) {').replace('    return ','        result = ')
 .replace(' & 1;\n}',' & 1;\n    }\n    return result;\n}');
getter='/* Generated by native/tools/generate-campaign-flags.cjs from accepted\n * func_00048abc. Bound the event VM byte ID to the 40 saved road flags. */\n'+getter;
fs.writeFileSync(path.join(native,'game/campaign/road-get.c'),getter);
const work=path.join(native,'build/campaign-flags');
function qualify(name,source,start,address,size,g={headers:[],bindings:{},sections:{'.text':address}}){
 const bytes=fs.readFileSync(path.join(native,'game',source));
 const built=compile(native,{...g,name:'campaign_'+name},bytes,work);
 const section=built.linked['.text'];assert.equal(section.address,address);
 assert(section.bytes.subarray(size).every(b=>b===0),'Road helper exceeds original owner');
 const sy=built.linked['.symtab'].bytes;
 for(let at=0;at<sy.length;at+=16)if((sy[at+12]&15)===2 && sy.readUInt32BE(at+8))
  assert(sy.readUInt32BE(at+4)+sy.readUInt32BE(at+8)<=address+size,'Function extent exceeds original owner');
 const code=Buffer.concat([section.bytes.subarray(0,size),Buffer.alloc(Math.max(0,size-section.size))]);
 return {start,address,size,source,sourceSha256:digest(bytes).toLowerCase(),sha256:digest(code).toLowerCase(),padToOwner:true,headers:[],symbols:{}};
}
const originalGetter=qualify('original_get',accepted.source.replace(/^game\//,''),0x48abc,0x80172bbc,52,accepted);
assert.equal(originalGetter.sha256,accepted.parts.find(p=>p.code).sha256.toLowerCase());
const set=qualify('event_set','campaign/road-flags.c',0x48a68,0x80172b68,84);
const get=qualify('event_get','campaign/road-get.c',0x48abc,0x80172bbc,52);
fs.writeFileSync(path.join(native,'game/campaign/flag-owners.json'),JSON.stringify({generator:'native/tools/generate-campaign-flags.cjs',originalGetter,set,get},null,2)+'\n');
console.log('Qualified bounded road setter/getter in their original 84/52-byte owners; accepted getter reproduced exactly.');
