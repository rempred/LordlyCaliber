// Generate the bounded Director adaptation from its accepted matching owner.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(__dirname,'..');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'game/accepted/rom-owners.json')));
const owner=catalog.sources.find(x=>x.name==='func_00284288');
const original=fs.readFileSync(path.join(root,owner.source));
if(crypto.createHash('sha256').update(original).digest('hex').toUpperCase()!==owner.sourceSha256)throw Error('Accepted Director source changed');
let source=original.toString('utf8').replace(/\r\n/g,'\n');
function replace(from,to){if(source.split(from).length!==2)throw Error('Director adaptation boundary changed');source=source.replace(from,to);}
replace('s32 func_00284288(void) {',
`int lc_scene_flag_get(int id);
void lc_scene_flag_set(int id,int unused,int value);
void lc_scene_sprite_command(u32 command,u32 value);
void lc_scene_sprite_cancel(int slot);
int lc_scene_sprite_busy(int slot);
s32 func_00284288(void) {`);
replace('switch (command) {',`if(command == 0x46 || (command == 0x63 && ((u32 *)command_address)[10] == 0xffffffffU))
            lc_scene_sprite_cancel(((u32 *)command_address)[1] & 255);
        if(command == 0x66) lc_scene_sprite_cancel(((s32 *)command_address)[1]);
        if(command == 0x7d) lc_scene_sprite_cancel(-1);
        switch (command) {`);
replace('case 0x8E:\n            cursor += 2;',`case 0x8E:
            if(command == 0x8E && (((u32 *)command_address)[1] & 0xffff0000U) == 0x4c430000U) {
                u32 flag = ((u32 *)command_address)[1] & 0xffffU;
                u32 operation = ((u32 *)command_address)[2];
                if(flag < 768U && operation < 3U)
                    lc_scene_flag_set(flag,0,operation == 2U ? !lc_scene_flag_get(flag) : operation);
            }
            if(command == 0x8E) lc_scene_sprite_command(((u32 *)command_address)[1],((u32 *)command_address)[2]);
            cursor += 2;`);
replace(`command_result = func_00045df4(
                (s16) ((*(s32 *)((s8 *)(((s32 *)(cursor * 4 + (s32)stream))) + (0xC))) + 0xAA));`,
`if((((u32 *)command_address)[3] & 0xffff0000U) == 0x4c430000U)
                command_result = lc_scene_flag_get(((u32 *)command_address)[3] & 0xffffU);
            else if((((u32 *)command_address)[3] & 0xffff0000U) == 0x4c4d0000U)
                command_result = lc_scene_sprite_busy(((u32 *)command_address)[3] & 0xffffU);
            else command_result = func_00045df4(
                (s16) ((*(s32 *)((s8 *)(((s32 *)(cursor * 4 + (s32)stream))) + (0xC))) + 0xAA));`);
fs.writeFileSync(path.join(root,'game/director/story-logic.c'),`/* Generated by native/tools/generate-scene-logic.cjs from accepted ${owner.name}.\n * Tagged 8E writes and 8F reads use the project's saved story-flag services.\n * Untagged retail commands retain their original behavior. */\n`+source+'\n'+fs.readFileSync(path.join(root,'game/director/story-sprites.c'),'utf8'));
const rom=fs.readFileSync(process.argv[2]||path.join(root,'../../Ogre Battle 64 - Person of Lordly Caliber (USA).z64'));
const part=owner.parts[0], bytes=rom.subarray(part.start,part.start+part.size);
if(crypto.createHash('sha256').update(bytes).digest('hex').toUpperCase()!==part.sha256)throw Error('Original Director owner differs');
fs.writeFileSync(path.join(root,'game/director/story-logic.json'),JSON.stringify({generator:'native/tools/generate-scene-logic.cjs',sourceSha256:owner.sourceSha256,address:owner.address,bindings:owner.bindings,original:part,originalPrologue:bytes.subarray(0,8).toString('hex')},null,2)+'\n');
