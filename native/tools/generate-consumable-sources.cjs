'use strict';
// Developer migration from accepted ASM reference to symbolic assembler source.
// Users only need the generated maintained source and authenticated compiler.
// No machine-code payload or private ROM data is emitted.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'../..');
const effects=require(path.join(root,'consumable-effects.js'));
const rom=fs.readFileSync(process.argv[2]),reference=fs.readFileSync(process.argv[3],'utf8');
if(rom.readUInt32BE(0)===0x37804012)rom.swap16();
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
if(sha(rom)!=='571e83396bc81e70da4c0a20313d82dbd7dfe685f2c37418c8e27f927e2cc67a')throw Error('US Rev0 required');
const start=0x41098,end=0x415fc,ram=0x8016b198;
const rows=[...reference.matchAll(/\/\* 0x([0-9A-F]{8}) 0x[0-9A-F]{8} 0x([0-9A-F]{8}) \*\/ \.word 0x[0-9A-F]{8} # (.+)/g)]
  .map(m=>({at:parseInt(m[1],16),word:parseInt(m[2],16),text:m[3].trim()}));
if(rows.length*4!==end-start||rows.some((r,i)=>r.at!==start+i*4||rom.readUInt32BE(r.at)!==r.word))throw Error('Reference source mismatch');
const symbols=new Map();
const calls = {};
const models=effects.MODEL_ORDER.map(key=>{
  const def=effects.MODEL_DEFS[key],name='LC_'+key.replace(/([a-z0-9])([A-Z])/g,'$1_$2').toUpperCase();
  const result={key,projectKey:def.projectKey,kind:def.kind,itemIds:def.itemIds,
    domainMin:def.domainMin,domainMax:def.domainMax,target:def.target};
  const fields=def.kind==='magnitude'?def.magnitudeOffsets.map(at=>[at,'magnitude',name]):
    [[def.minimumOffset,'minimum',name+'_MIN'],[def.widthOffset,'width',name+'_WIDTH']];
  result.fields=fields.map(([at,kind,symbol])=>{
    if(symbols.has(at))throw Error('Duplicate effect parameter');
    symbols.set(at,symbol);
    return {offset:at-start,kind,symbol,retail:rom.readUInt32BE(at)};
  });
  return result;
});
const label=at=>'L_'+at.toString(16);
const out=['/* Generated by native/tools/generate-consumable-sources.cjs from accepted',
  ' * func_00041098.s and consumable-effects.js definitions. US Rev0 resident',
  ' * RAM8016B198, ROM41098. Parameters are defined by the exporter.',
  ' * Preserve instruction positions: the original dispatch table points here.',
  ' */','.set noat','.set noreorder'];
for(const row of rows){
  const {at,word}=row,op=word>>>26;
  let text=row.text;
  if(op===1||(op>=4&&op<=7)||(op>=20&&op<=23)){
    const target=at+4+((word<<16)>>16)*4;
    if(target<start||target>=end)throw Error('External conditional branch');
    text=text.replace(/0x[0-9A-Fa-f]+$/,label(target));
  }else if(op===2||op===3){
    const target=(0x80000000|((word&0x3ffffff)<<2))>>>0;
    const local=target>=ram&&target<ram+end-start;
    const name=local?label(start+target-ram):'service_'+target.toString(16);
    if(!local)calls[name]=target;
    text=(op===2?'j ':'jal ')+name;
  }else if(op===0&&(word&63)===13){
    if ((word>>>6)&1023) throw Error('Unsupported break subcode');
    text=`break ${(word>>>16)&1023}`; // GNU 2.6 accepts the original single code
  }else if(op===0&&(word&63)===26){
    text=text.replace(/^div /,'div $zero, '); // suppress assembler's division macro
  }else if(text.startsWith('move ')){
    text=text.replace('move ',(word&63)===33?'addu ':'or ')+', $zero';
  }
  if(symbols.has(at))text=text.replace(/[^,]+$/, ' '+symbols.get(at));
  out.push(label(at)+':','    '+text);
}
const output=path.join(root,'native/game/consumables');
fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(path.join(output,'effects.s'),out.join('\n')+'\n');
fs.writeFileSync(path.join(output,'effects.json'),JSON.stringify({
  generator:'native/tools/generate-consumable-sources.cjs',
  input:'Accepted Decomp ASM func_00041098.s; US Rev0 z64 SHA256 '+sha(rom),
  start,size:end-start,address:ram,retailSha256:sha(rom.subarray(start,end)),
  dispatch:{start:0x65d60,size:76,retailSha256:sha(rom.subarray(0x65d60,0x65dac))},calls,models
},null,2)+'\n');
console.log(`Generated symbolic source: ${rows.length} instructions, ${models.length} models, ${symbols.size} parameter words`);
