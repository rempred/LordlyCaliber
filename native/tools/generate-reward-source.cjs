'use strict';
// Authenticated ASM -> maintained source. No compiled game payload is distributed.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),cp=require('node:child_process');
const mips=require('./lib/symbolic-mips.cjs'),root=path.resolve(__dirname,'../..');
const rom=fs.readFileSync(process.argv[2]),reference=fs.readFileSync(process.argv[3],'utf8');
if(rom.readUInt32BE(0)===0x37804012)rom.swap16();
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
if(hash(rom)!=='571e83396bc81e70da4c0a20313d82dbd7dfe685f2c37418c8e27f927e2cc67a')throw Error('US Rev0 required');
const start=0x101ddc,end=0x102f00,ram=0x801ad69c,calls={service_8009da50:0x8009da50};
// Descriptor 7 proves this placement independently of the nominal ASM comments.
const descriptor=0x387c0+7*40;
if(rom.readUInt32BE(descriptor)+(start-rom.readUInt32BE(descriptor+8))!==ram ||
   start<rom.readUInt32BE(descriptor+8)||end>rom.readUInt32BE(descriptor+12))throw Error('Overlay placement differs');
const rows=mips.rows(reference,rom,start,end);
// The original frame reserves 0x50 bytes, saved registers start at +0x38.
// +0x20..+0x2f is otherwise unused. DMA is at least 8-byte aligned and does not touch
// the argument home area or the cache line containing saved registers.
const selector=[
 'lui $a0, LC_REWARDS_HI','ori $a0, $a0, LC_REWARDS_LO',
 'sll $v0, $s4, 4','addu $a0, $a0, $v0','addiu $a1, $sp, 0x20',
 'jal service_8009da50','addiu $a2, $zero, 16',
 'jal service_80092a60','nop',
 'lhu $t0, 0x26($sp)','lhu $t1, 0x28($sp)','lhu $t2, 0x2a($sp)',
 'addu $t1, $t1, $t0','addu $t2, $t2, $t1',
 'divu $zero, $v0, $t2','mfhi $v0',
 'sltu $v1, $v0, $t0','xori $v1, $v1, 1',
 'sltu $v0, $v0, $t1','xori $v0, $v0, 1',
 'addu $v0, $v0, $v1','sll $v0, $v0, 1','addu $v0, $sp, $v0',
 'lhu $s3, 0x20($v0)','lui $v0, 0x8019','lbu $v0, 0x3670($v0)',
 'nop','nop','nop','nop'];
if(selector.length*4!==0x1024d4-0x10245c)throw Error('Wrong selector extent');
const customSelector=['jal lc_custom_reward','nop','bgez $v0, L_1024cc','addu $s3, $v0, $zero',...selector.slice(0,26)];
const out=['/* Generated by native/tools/generate-reward-source.cjs from accepted',
 ' * func_00101DDC.s. Descriptor 7: ROM101DDC -> RAM801AD69C.',
 ' * Native mode replaces the class reward selection only. All other positions',
 ' * remain unchanged. Rows are 3 u16 rewards, 3 u16 weights, 4 reserved bytes.',
 ' * Every byte-sized class has a ROM row; validated totals are nonzero. */',
 '.set noat','.set noreorder','.ifndef LC_CUSTOM_SQUADS','.equ LC_CUSTOM_SQUADS,0','.endif'];
for(const row of rows){
 const original=mips.instruction(row,{start,end,ram,calls});
 out.push(mips.label(row.at)+':');
 if(row.at>=0x10245c&&row.at<0x1024d4)out.push('.if LC_NATIVE_REWARDS','.if LC_CUSTOM_SQUADS','    '+customSelector[(row.at-0x10245c)/4],'.else','    '+selector[(row.at-0x10245c)/4],'.endif','.else','    '+original,'.endif');
 else out.push('    '+original);
}
const source=out.join('\n')+'\n',output=path.join(root,'native/game/encounters');

const toolDir=path.resolve(process.argv[4]),pins=JSON.parse(fs.readFileSync(path.join(root,'native/rebuild/toolchain.json'))).tools;
for(const [name,expected] of Object.entries(pins))if(hash(fs.readFileSync(path.join(toolDir,name)))!==expected.toLowerCase())throw Error('Compiler identity mismatch: '+name);
const build=path.join(root,'native/build/reward-source');fs.mkdirSync(build,{recursive:true});
fs.writeFileSync(path.join(build,'owner.ld'),Object.entries({...calls,lc_custom_reward:0x80188000}).map(([n,a])=>`${n} = 0x${a.toString(16)};`).join('\n')+`\nSECTIONS { .owner 0x${ram.toString(16)} : { *(.owner) } }\n`);
function assemble(native,custom=false){
 const base=path.join(build,(native?'native':'retail')+(custom?'_custom':''));
 fs.writeFileSync(base+'.s',`.section .owner,"ax"\n.balign 4\n.equ LC_CUSTOM_SQUADS,${custom?1:0}\n.equ LC_NATIVE_REWARDS,${native?1:0}\n.equ LC_REWARDS_HI,640\n.equ LC_REWARDS_LO,0\n`+source);
 cp.execFileSync(path.join(toolDir,'mips-kmc-elf-as.exe'),['--vr4300mul-off','-G','0','-mips3','-mabi=32','-EB','-o',base+'.o',base+'.s']);
 cp.execFileSync(path.join(toolDir,'mips-kmc-elf-ld.exe'),['-EB','-T',path.join(build,'owner.ld'),'-o',base+'.elf',base+'.o']);
 cp.execFileSync(path.join(toolDir,'mips-kmc-elf-objcopy.exe'),['-O','binary',...['.text','.data','.bss','.reginfo','.mdebug','.pdr','.comment'].map(s=>'--remove-section='+s),base+'.elf',base+'.bin']);
 return fs.readFileSync(base+'.bin');
}
const retail=assemble(false);if(!retail.equals(rom.subarray(start,end)))throw Error('Compiled retail reward owner mismatch');
const native=assemble(true);if(native.length!==end-start)throw Error('Native reward owner exceeds original extent');
const masked=Buffer.from(native);for(const at of [0x10245e,0x102462])masked.writeUInt16BE(0,at-start);
const hooked=assemble(true,true),at=0x10245c-start;
if(hooked.readUInt32BE(at)!==(0x0c000000|((0x80188000>>>2)&0x3ffffff)))throw Error('Wrong custom reward target');
if(hooked.length!==native.length||!hooked.subarray(at+16,at+120).equals(native.subarray(at,at+104)))throw Error('Custom selector changed class reward behavior');
const customPrefix={offset:at,size:120,entry:'lc_custom_reward',words:[0,hooked.readUInt32BE(at+4),hooked.readUInt32BE(at+8),hooked.readUInt32BE(at+12)]};
const restored=Buffer.from(hooked);native.copy(restored,at,at,at+120);
if(!restored.equals(native))throw Error('Custom selector changed another instruction');
const patches=require('./lib/owner-hooks.cjs')(source,output,'rewards',start,ram,[[0x10245c,0x1024d4]]);
fs.writeFileSync(path.join(output,'rewards.json'),JSON.stringify({acceptedC:true,patches,generator:'native/tools/generate-reward-source.cjs',
 input:'Accepted Decomp ASM func_00101DDC.s; US Rev0 z64 SHA256 '+hash(rom),start,size:end-start,address:ram,
 retailSha256:hash(retail),nativeMaskedSha256:hash(masked),calls,customPrefix,
 dma:{start:0x2de50,size:164,sha256:hash(rom.subarray(0x2de50,0x2def4))},
 overlay:{start:descriptor,size:40,sha256:hash(rom.subarray(descriptor,descriptor+40))}},null,2)+'\n');
console.log(`Compiled ${rows.length} instructions: retail exact; native selection fits original 120-byte block`);
